"""Demo models for the plugin: Apple DCFs built by deskstack, each with one planted error.

Brief M5: "associate + VP catch planted errors in 10 demo models". Each demo
says which reviewer must catch it:
- `checker`: rule ids the /vp-review checker must raise;
- `tieout`: per cell, the verify_value status (and a hint pattern) /associate must report.

The tie-out half needs the server's verify_value, so `fixture()` exports the
extracted batches plus expectations to server/test/fixtures/demo/extract.json,
where a Vitest test runs them against Apple's SEC fixture. A pytest checks the
committed file is current. Regenerate with:  python tests/demo_models.py
"""

from __future__ import annotations

import copy
import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE.parent))

from deskstack_check.build import build_dcf  # noqa: E402
from deskstack_check.tieout import extract  # noqa: E402

SPEC = json.loads((HERE / "specs" / "aapl_dcf.json").read_text())
FIXTURE = HERE.parent.parent / "server" / "test" / "fixtures" / "demo" / "extract.json"


def _hist(key: str, idx: int, value: float):
    def f(spec):
        spec["history"]["lines"][key]["values"][idx] = value

    return f


def _all_hist(key: str, fn):
    def f(spec):
        v = spec["history"]["lines"][key]["values"]
        spec["history"]["lines"][key]["values"] = [fn(x) for x in v]

    return f


def _bridge(key: str, value: float):
    def f(spec):
        spec["bridge"][key]["value"] = value

    return f


def _assume(key: str, value: float):
    def f(spec):
        spec["assumptions"][key]["value"] = value

    return f


def _drop_source(ref: str):
    def t(b):
        b.sources = [s for s in b.sources if s[0] != ref]

    return t


def _formula(sheet: str, coord: str, formula: str, value=None):
    def t(b):
        b.sheet(sheet)[coord].value = formula
        if value is not None:
            b.cached[(sheet, coord)] = value(b) if callable(value) else value

    return t


def _mid_year_yes(b):
    ws = b.sheet("Inputs")
    for row in ws.iter_rows():
        if row[0].value == "Mid-year convention":
            row[1].value = "Yes"


# name, spec mutation, tamper, expected checker rules, expected tie-out {ref: (status, hint regex or None)}
DEMOS = [
    ("clean", None, None, [], {}),
    ("revenue-scale", _hist("revenue", 2, 416161000), None, [], {"Inputs!D5": ("mismatch", "Scale: the value matches if it is in thousands")}),
    ("revenue-typo", _hist("revenue", 1, 391053), None, [], {"Inputs!C5": ("mismatch", None)}),
    ("capex-sign", _all_hist("capex", lambda x: -x), None, [], {f"Inputs!{c}8": ("mismatch", "Sign: the value has the opposite sign") for c in "BCD"}),
    ("ebit-is-gross-profit", _hist("operating_income", 2, 195201), None, [], {"Inputs!D6": ("mismatch", "Line item: the value matches gross_profit")}),
    ("net-debt-last-year", _bridge("net_debt", 41458), None, [], {"Inputs!B22": ("mismatch", "Period: the value matches net_debt for FY2024")}),
    ("shares-in-units", _bridge("diluted_shares", 15004697000), None, [], {"Inputs!B23": ("mismatch", "Scale: the value matches if it is in units")}),
    ("unsourced-input", None, _drop_source("Inputs!D6"), ["DS004"], {"Inputs!D6": ("match", None)}),
    ("hardcode-in-formula", None, _formula("DCF", "E4", "=D4*1.05", lambda b: b.cached[("DCF", "D4")] * 1.05), ["DS001"], {}),
    ("fcf-forgets-capex", None, _formula("DCF", "F10", "=F7+F8", lambda b: b.cached[("DCF", "F7")] + b.cached[("DCF", "F8")]), ["DS002"], {}),
    ("terminal-growth-too-high", _assume("terminal_growth", 0.075), None, ["DS011", "DS012"], {}),
    ("mid-year-stated-not-applied", None, _mid_year_yes, ["DS015"], {}),
]


def build_demo(name: str, outdir: Path) -> Path:
    _, mut, tamper, _, _ = next(d for d in DEMOS if d[0] == name)
    spec = copy.deepcopy(SPEC)
    if mut:
        mut(spec)
    return build_dcf(spec, outdir / f"{name}.xlsx", tamper=tamper)


def fixture(outdir: Path) -> dict:
    demos = []
    for name, _, _, _, tie in DEMOS:
        ex = extract(str(build_demo(name, outdir)))
        demos.append({
            "name": name,
            "batches": ex["verify_batches"],
            "expect": {ref: {"status": s, "hint": h} for ref, (s, h) in tie.items()},
        })
    return {"_note": "Generated by checker/tests/demo_models.py. Do not edit by hand.", "demos": demos}


if __name__ == "__main__":
    import tempfile

    with tempfile.TemporaryDirectory() as d:
        data = fixture(Path(d))
    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text(json.dumps(data, indent=1) + "\n")
    print(f"Wrote {FIXTURE}")
