#!/usr/bin/env python3
"""Copy the checker and its pure-Python dependencies into each skill that runs scripts.

Why: in claude.ai chat each skill's folder is copied on its own into the code
sandbox, and openpyxl isn't guaranteed to be installed there (installs may be
blocked). So every skill that runs scripts carries its own copy under
`scripts/_vendor/`. `checker/` stays the single source of truth.

  python3 plugins/sync_vendor.py           # write the copies
  python3 plugins/sync_vendor.py --check   # exit 1 if a copy is out of date (used by the tests)

Uses the openpyxl and et_xmlfile installed next to the checker (checker/.venv), pinned below.
"""

from __future__ import annotations

import hashlib
import importlib.util
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CHECKER = ROOT / "checker" / "deskstack_check"
PLUGIN = ROOT / "plugins" / "deskstack"
SKILLS = ["analyst", "associate", "vp-review", "md-redteam", "compliance", "sign-off"]
PINS = {"openpyxl": "3.1.5", "et_xmlfile": "2.0.0"}
# SHA-256 of every third-party file, written by sync(): --check compares the copies with it, so it needs no
# installed openpyxl and gives the same answer on every machine.
MANIFEST = ROOT / "plugins" / "vendor.sha256.json"
LAUNCHER = '''#!/usr/bin/env python3
"""deskstack scripts (vendored copy of checker/deskstack_check, openpyxl and et_xmlfile; see _vendor/NOTICE.md).

  python3 deskstack.py check MODEL.xlsx [--json] [--audit FINDINGS.md]
  python3 deskstack.py extract MODEL.xlsx
  python3 deskstack.py tieout MODEL.xlsx RESULTS.json [--json]
  python3 deskstack.py build SPEC.json OUT.xlsx
  python3 deskstack.py hash MODEL.xlsx
  python3 deskstack.py sensitivity MODEL.xlsx [--price P]
  python3 deskstack.py compliance MODEL.xlsx [--memo MEMO.md]
  python3 deskstack.py signoff MODEL.xlsx --tieout T.json --review R.json --compliance C.json [--redteam M.md]
        [--approve "USER'S WORDS" --by NAME --out FINAL.xlsx [--accept-open "REASON"]]

Generated by plugins/sync_vendor.py. Do not edit here.
"""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "_vendor"))

from deskstack_check.__main__ import main  # noqa: E402

sys.exit(main(sys.argv[1:]))
'''
NOTICE = """# Vendored code

Generated by `plugins/sync_vendor.py`. Do not edit here; edit `checker/` and re-run it.

| Package | Version | License | Source |
|---|---|---|---|
| deskstack_check | (this repo) | MIT | `checker/deskstack_check` |
| openpyxl | {openpyxl} | MIT | https://foss.heptapod.net/openpyxl/openpyxl (`licenses/openpyxl-LICENCE.rst`) |
| et_xmlfile | {et_xmlfile} | MIT, with parts under the PSF license | https://foss.heptapod.net/openpyxl/et_xmlfile (`licenses/et_xmlfile-*`) |
"""


def _site(pkg: str) -> Path:
    venv = sorted((ROOT / "checker" / ".venv" / "lib").glob("python*/site-packages"))
    roots = venv + [Path(p) for p in sys.path if p]
    for r in roots:
        if (r / pkg).is_dir() and list(r.glob(f"{pkg}-{PINS[pkg]}.dist-info")):
            return r
    spec = importlib.util.find_spec(pkg)
    raise SystemExit(f"{pkg}=={PINS[pkg]} not found (found {spec.origin if spec else 'none'}). "
                     f"Run: python3 -m venv checker/.venv && checker/.venv/bin/pip install openpyxl=={PINS['openpyxl']}")


def _ignore(_dir, names):
    return [n for n in names if n == "__pycache__" or n.endswith(".pyc")]


def _expected() -> dict[str, Path]:
    """Relative path inside _vendor -> source file."""
    files: dict[str, Path] = {}
    for f in CHECKER.rglob("*.py"):
        if "__pycache__" not in f.parts:
            files[f"deskstack_check/{f.relative_to(CHECKER)}"] = f
    for pkg in PINS:
        site = _site(pkg)
        for f in (site / pkg).rglob("*"):
            if f.is_file() and "__pycache__" not in f.parts and f.suffix != ".pyc":
                files[f"{pkg}/{f.relative_to(site / pkg)}"] = f
        dist = next(site.glob(f"{pkg}-{PINS[pkg]}.dist-info"))
        for lic in dist.glob("LICEN*"):
            files[f"licenses/{pkg}-{lic.name}"] = lic
    return files


def _sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def _checker_files() -> dict[str, Path]:
    return {f"deskstack_check/{f.relative_to(CHECKER)}": f for f in CHECKER.rglob("*.py") if "__pycache__" not in f.parts}


def _manifest() -> dict[str, str]:
    return json.loads(MANIFEST.read_text())


def sync() -> None:
    files = _expected()
    MANIFEST.write_text(json.dumps({r: _sha(f) for r, f in sorted(files.items()) if not r.startswith("deskstack_check/")}, indent=1) + "\n")
    for skill in SKILLS:
        scripts = PLUGIN / "skills" / skill / "scripts"
        vendor = scripts / "_vendor"
        if vendor.exists():
            shutil.rmtree(vendor)
        for rel, src in files.items():
            dst = vendor / rel
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dst)
        (vendor / "NOTICE.md").write_text(NOTICE.format(**PINS))
        (scripts / "deskstack.py").write_text(LAUNCHER)
    print(f"Synced {len(files)} files into {', '.join(SKILLS)}.")


def check() -> int:
    want_sha = {**{r: _sha(f) for r, f in _checker_files().items()}, **_manifest()}
    stale = []
    for skill in SKILLS:
        scripts = PLUGIN / "skills" / skill / "scripts"
        vendor = scripts / "_vendor"
        have = {str(p.relative_to(vendor)) for p in vendor.rglob("*") if p.is_file() and "__pycache__" not in p.parts} if vendor.exists() else set()
        want = set(want_sha) | {"NOTICE.md"}
        stale += [f"{skill}: missing {r}" for r in sorted(want - have)]
        stale += [f"{skill}: extra {r}" for r in sorted(have - want)]
        stale += [f"{skill}: differs {r}" for r, sha in want_sha.items() if r in have and _sha(vendor / r) != sha]
        if not (scripts / "deskstack.py").exists() or (scripts / "deskstack.py").read_text() != LAUNCHER:
            stale.append(f"{skill}: launcher out of date")
    if stale:
        print("Vendored copies are out of date (run: python3 plugins/sync_vendor.py):\n  " + "\n  ".join(stale[:20]))
        return 1
    print("Vendored copies are current.")
    return 0


if __name__ == "__main__":
    sys.exit(check() if "--check" in sys.argv else (sync() or 0))
